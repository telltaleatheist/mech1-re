/* Class C (docs/phase2/PLAN.md 8.3): the geometry tables, computed. Each entry
 * is the floor of its value, which lies at least 2e-4 from an integer
 * (measured at 50 digits); the entries that are exact integers are written as
 * such, so no rounding of the libm decides them. */
static const double kPi=3.14159265358979323846;
static double Floored(double value,int16_t *entry)
{
    double floored=floor(value);
    *entry=(int16_t)floored;
    double margin=value-floored;
    return margin<1.0-margin?margin:1.0-margin;
}
static void PutWord(uint8_t *at,size_t index,int16_t value)
{at[index*2]=(uint8_t)((uint16_t)value&0xFF);at[index*2+1]=(uint8_t)((uint16_t)value>>8);}
/* 22B6:486D, 0x801 words: 16384 cos(i pi / 2048), rounded down. */
static double GenerateOrientationCosines(uint8_t *at)
{
    double margin=1.0;
    for (size_t i=0;i<=0x800;++i)
    {
        int16_t entry;
        if (i==0) entry=16384;
        else if (i==0x400) entry=0;
        else if (i==0x800) entry=-16384;
        else {double m=Floored(16384.0*cos((double)i*kPi/2048.0),&entry);if (m<margin) margin=m;}
        PutWord(at,i,entry);
    }
    return margin;
}
/* 22B6:586F, 0x402 words: asin(i/512) for 0..200, then acos(j/512) for
 * j = i-201, 0..200, each in units of pi/2048, rounded down. */
static double GenerateCoefficientAngles(uint8_t *at)
{
    double margin=1.0;
    for (size_t i=0;i<0x402;++i)
    {
        int16_t entry;
        if (i==0 || i==0x401) entry=0;
        else if (i==0x200 || i==0x201) entry=1024;
        else
        {
            double angle=i<0x200?asin((double)i/512.0):acos((double)(i-0x201)/512.0);
            double m=Floored(angle*2048.0/kPi,&entry);if (m<margin) margin=m;
        }
        PutWord(at,i,entry);
    }
    return margin;
}
